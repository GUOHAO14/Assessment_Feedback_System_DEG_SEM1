    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        JTextField nameField = new JTextField(25);
        JTextField emailField = new JTextField(25);
        JComboBox<Leader> leaderList = new JComboBox<>();
        for(Leader x : InteractTxt.allLeader){
            leaderList.addItem(x);
        }

        JPanel panel = new JPanel(new GridLayout(0, 1));
        panel.add(new JLabel("Name:"));
        panel.add(nameField);
        panel.add(new JLabel("Email:"));
        panel.add(emailField);
        panel.add(new JLabel("Leader:"));
        panel.add(leaderList);

        while (true) {
            int result = JOptionPane.showConfirmDialog(this, panel, "New Lecturer", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
            if (result != JOptionPane.OK_OPTION) break;
            
            if (result == JOptionPane.OK_OPTION) {
                String name = nameField.getText().trim();
                String email = emailField.getText().trim();
                Leader leader = (Leader) leaderList.getSelectedItem();
                
                ValidationResult nameResult = ErrorChecking.checkInput(name);
                ValidationResult emailResult = ErrorChecking.checkEmail(email);
                
                if (nameResult != ValidationResult.OK) {
                    showNameError(nameResult);
                }else if (emailResult != ValidationResult.OK) {
                    showEmailError(emailResult);
                }else{
                    String id = User.getNewLcID();

                    String password = User.GeneratePW();

                    String [] userdata = {id, name, email, password, "lecturer"};
                    InteractTxt.allLecturer.add(new Lecturer(userdata));

                    InteractTxt.checkLecID(id).setLeader(leader);
                    leader.leaderTeam.add(InteractTxt.checkLecID(id));

                    InteractTxt.writeUser();
                    Lecturer New = InteractTxt.checkLecID(id);
                    model.addRow(new String[]{New.getId(), New.getName(), New.getEmail(), New.getLeader().getId()});
                    break;
                }
            }
        }
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void LecturerTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_LecturerTableMouseClicked
        int row = LecturerTable.getSelectedRow();
        Lecturer Lec = InteractTxt.allLecturer.get(row);

        JTextField nameField = new JTextField(25);
        nameField.setText(Lec.getName());
        JTextField emailField = new JTextField(25);
        emailField.setText(Lec.getEmail());
        JComboBox<Leader> leaderList = new JComboBox<>();
        for(Leader x : InteractTxt.allLeader){
            leaderList.addItem(x);
        }
        leaderList.setSelectedItem(Lec.getLeader());

        JPanel panel = new JPanel(new GridLayout(0, 1));
        panel.add(new JLabel("Name:"));
        panel.add(nameField);
        panel.add(new JLabel("Email:"));
        panel.add(emailField);
        panel.add(new JLabel("Leader:"));
        panel.add(leaderList);

        while (true) {
            Object[] options = {"OK", "Delete", "Cancel"};
            int result = JOptionPane.showOptionDialog(this,panel,Lec.getId(),JOptionPane.DEFAULT_OPTION,JOptionPane.PLAIN_MESSAGE,null,options,options[2]);
            if (result != 0 && result != 1) break;

            if (result == 0) {
                String name = nameField.getText().trim();
                String email = emailField.getText().trim();
                Leader leader = (Leader) leaderList.getSelectedItem();
                String leaderId = leader.getId();
                
                ValidationResult nameResult = ErrorChecking.checkInput(name);
                ValidationResult emailResult = ErrorChecking.checkEmail(email);
                
                if (nameResult != ValidationResult.OK) {
                    showNameError(nameResult);
                }else if (emailResult != ValidationResult.OK && !email.equals(Lec.getEmail())) {
                    showEmailError(emailResult);
                }else{
                    Lec.setName(name);
                    Lec.setEmail(email);
                    Lec.getLeader().leaderTeam.remove(Lec);
                    Lec.setLeader(leader);
                    Lec.getLeader().leaderTeam.add(Lec);

                    InteractTxt.writeUser();

                    model.setValueAt(name, row, 1);
                    model.setValueAt(email, row, 2);
                    model.setValueAt(leaderId, row, 3);
                    break;
                }
            }
            
            if (result == 1) {
                int confirm = JOptionPane.showConfirmDialog(this, "Do you sure to delete the Lecturer?", "Confirm", JOptionPane.YES_NO_OPTION);
                if (confirm == JOptionPane.OK_OPTION) {
                    InteractTxt.allLecturer.remove(Lec);
                    for (project.roles.Class x : Lec.Lec_Classes){
                        x.setLecId("NA");
                    }
                    Lec.getLeader().leaderTeam.remove(Lec);
                    for (project.roles.Module x : Lec.Lec_Modules){
                        x.Mod_Lecturers.remove(Lec);
                    }

                    Lec.Lec_Modules.clear();
                    Lec.Lec_Classes.clear();

                    InteractTxt.saveDatabase();
                    model.removeRow(row);
                    break;
                }
            }
        }
        
    }//GEN-LAST:event_LecturerTableMouseClicked

    private void jTextField1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTextField1ActionPerformed
        String input = jTextField1.getText().trim();
        ArrayList<Lecturer> matched = Lecturer.search(input);
        model.setRowCount(0);
        if (matched.isEmpty()) {
            for(Lecturer x : InteractTxt.allLecturer){
                model.addRow(new String[]{x.getId(), x.getName(), x.getEmail(), x.getLeader().getId()});
            }
            JOptionPane.showMessageDialog(this, input + " Doesn't Have Any Matched Result", "Unable To Found", JOptionPane.ERROR_MESSAGE);
        } else {
            for(Lecturer x : matched){
                model.addRow(new Object[]{x.getId(), x.getName(), x.getEmail(), x.getLeader().getId()});
            }
        }
    }//GEN-LAST:event_jTextField1ActionPerformed

